from playwright.sync_api import sync_playwright
from pathlib import Path
Path('qa-output').mkdir(exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 page=browser.new_page(viewport={'width':1440,'height':1050},device_scale_factor=1)
 errors=[]
 page.on('pageerror',lambda error:errors.append(str(error)))
 page.goto('http://127.0.0.1:8080')
 page.get_by_role('button',name='Use admin',exact=True).click()
 page.get_by_role('button',name='Sign in',exact=True).click()
 page.get_by_role('heading',name='Your competition, in focus.').wait_for()
 page.screenshot(path='qa-output/dashboard.png',full_page=True)
 page.get_by_role('button',name='Record score',exact=True).click()
 page.locator('#f-game_id').select_option('1')
 page.locator('#f-points').fill('9900')
 page.locator('#f-note').fill('Browser integration test')
 page.locator('#modal').get_by_role('button',name='Record score',exact=True).click()
 page.wait_for_function("!document.querySelector('#modal').open")
 page.get_by_role('button',name='Score history',exact=True).click()
 page.locator('#search').fill('Browser integration test')
 assert page.locator('#score-table tbody tr').count()==1
 page.locator('#score-table').get_by_role('button',name='Delete',exact=True).click()
 page.locator('#modal').get_by_role('button',name='Confirm',exact=True).click()
 page.wait_for_function("!document.querySelector('#modal').open")
 page.get_by_role('button',name='Concurrency lab',exact=True).click()
 page.locator('#race-count').select_option('7')
 page.get_by_role('button',name='Run concurrency test',exact=True).click()
 page.get_by_text('CAPACITY CHECK PASSED',exact=True).wait_for()
 assert page.locator('#lab-results tbody tr').count()==7
 page.screenshot(path='qa-output/concurrency.png',full_page=True)
 page.get_by_role('button',name='HTTP explorer',exact=True).click()
 page.get_by_role('button',name='Send request',exact=True).click()
 page.wait_for_function("document.querySelector('#http-status').textContent.startsWith('200')")
 assert 'Mohamed Moustafa' in page.locator('#json-response').inner_text()
 page.screenshot(path='qa-output/http.png',full_page=True)
 for name in ['Players','Games','Leaderboard','Analytics','Live arena','Activity log']:
  page.get_by_role('button',name=name,exact=True).click()
  assert page.locator('h1').inner_text()
 page.locator('#top-logout').click()
 page.get_by_role('button',name='Use player',exact=True).click()
 page.get_by_role('button',name='Sign in',exact=True).click()
 page.get_by_role('heading',name='Reflex Rush.',exact=True).wait_for()
 page.get_by_role('button',name='Start round',exact=True).click()
 page.get_by_text('ROUND LIVE',exact=True).wait_for()
 for _ in range(4):
  page.wait_for_timeout(250)
  g=page.evaluate("(() => { const g=rushGeometry(); return {x:g.rect.left+g.x,y:g.rect.top+g.y}; })()")
  page.mouse.click(g['x'],g['y'])
 page.get_by_text('Score saved automatically. Your arena seat is free.',exact=True).wait_for(timeout=35000)
 page.screenshot(path='qa-output/reflex-result.png',full_page=True)
 page.get_by_role('button',name='Overview',exact=True).click()
 page.get_by_role('heading',name='Ready to play, Mohamed?').wait_for()
 assert page.url.endswith('/player')
 assert page.get_by_role('button',name='Players',exact=True).count()==0
 page.get_by_role('button',name='Live arena',exact=True).click()
 page.get_by_role('button',name='Join arena',exact=True).click()
 page.get_by_role('button',name='Leave arena',exact=True).wait_for()
 page.get_by_role('button',name='Leave arena',exact=True).click()
 page.get_by_role('button',name='Join arena',exact=True).wait_for()
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='Overview',exact=True).click()
 page.screenshot(path='qa-output/mobile.png',full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
 assert errors==[],errors
 print('PASS: admin/player routing, score create/delete, concurrency race, HTTP explorer, all navigation, arena join/leave, mobile overflow, real Reflex Rush round with automatic score save, no JS errors.')
 browser.close()
